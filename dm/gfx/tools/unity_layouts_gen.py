#!/usr/bin/env python3
"""Writes unity_layouts.txt: the Shader (class 48) and ComputeShader (class 72) type trees of every Unity release from 5.5 on (the first with serialized format 17), for players whose serialized files carry no
type tree and that ship no bundle to borrow one from (Unspottable, Ultimate Chicken Horse, Raging Loop, Stick Fight ...). unityfs.py reads the file (layout_candidates).

The trees come from AssetRipper's TypeTreeDumps (https://github.com/AssetRipper/TypeTreeDumps, StructsDump/release/<version>.dump: the editor's own type trees, one dump per
Unity version). Only f (final) and p (patch) builds are read, the ones games ship with. A tree keeps what reading an object needs: each node's type and name, its children and its
"align after" flag (0x4000). 836 versions give 23 Shader and 10 ComputeShader trees; nodes shared between trees are written once.

    python unity_layouts_gen.py [--cache <folder for the downloaded class sections>] [--out unity_layouts.txt]

Run it again when AssetRipper adds Unity versions. It needs the network (raw.githubusercontent.com and api.github.com).
"""
import argparse
import concurrent.futures as cf
import json
import os
import re
import urllib.request
from pathlib import Path

REPO = 'AssetRipper/TypeTreeDumps'
CLASSES = (48, 72)
LINE = re.compile(r'^(\t*)(.+) (\S+) // ByteSize\{[0-9a-f]+\}, Index\{[0-9a-f]+\}, Version\{\d+\}, IsArray\{\d\}, MetaFlag\{([0-9a-f]+)\}$')
VERSION = re.compile(r'^(\d+)\.(\d+)\.(\d+)([fp])(\d+)$')


def vkey(v):
    m = VERSION.match(v); return (int(m[1]), int(m[2]), int(m[3]), m[4], int(m[5]))


def versions():
    req = urllib.request.Request(f'https://api.github.com/repos/{REPO}/git/trees/main?recursive=1', headers={'Accept': 'application/vnd.github+json'})
    tree = json.load(urllib.request.urlopen(req, timeout=60))['tree']
    out = []
    for t in tree:
        m = re.match(r'^StructsDump/release/(.+)\.dump$', t['path'])
        if m and VERSION.match(m[1]) and vkey(m[1])[:2] >= (5, 5): out.append(m[1])   # 5.5 is the first with serialized format 17, the oldest unityfs reads
    return sorted(out, key=vkey)


def section(v, cache):
    """the dump's lines for CLASSES only (a whole dump is about 2 MB)"""
    f = cache / f'{v}.txt'
    if f.is_file() and f.stat().st_size: return f.read_text(encoding='utf-8')
    raw = urllib.request.urlopen(f'https://raw.githubusercontent.com/{REPO}/main/StructsDump/release/{v}.dump', timeout=120).read().decode('utf-8')
    keep, out = False, []
    for ln in raw.splitlines():
        m = re.match(r'^// classID\{(\d+)\}', ln)
        if m: keep = int(m[1]) in CLASSES
        if keep: out.append(ln)
    text = '\n'.join(out) + '\n'
    f.write_text(text, encoding='utf-8')
    return text


def parse(text):
    """→ {class ID: [(depth, type, name, align after)]}"""
    out, cur = {}, None
    for ln in text.splitlines():
        m = re.match(r'^// classID\{(\d+)\}', ln)
        if m: cur = int(m[1]); out[cur] = []; continue
        m = LINE.match(ln)
        if m and cur is not None: out[cur].append((len(m[1]), m[2], m[3], bool(int(m[4], 16) & 0x4000)))
    return {c: n for c, n in out.items() if n}


def write(layouts, out):
    """layouts = {(class ID, nodes): [versions]} → the file unityfs.py reads"""
    ids, rows = {}, []

    def build(nodes, i):
        d, t, n, a = nodes[i]; kids = []; j = i + 1
        while j < len(nodes) and nodes[j][0] > d:
            k, j = build(nodes, j); kids.append(k)
        key = (t, n, a, tuple(kids))
        if key not in ids: ids[key] = len(ids); rows.append(key)
        return ids[key], j

    roots = []
    for (cid, nodes), vs in sorted(layouts.items(), key=lambda x: (x[0][0], vkey(x[1][0]))):
        root, end = build(list(nodes), 0); assert end == len(nodes)
        roots.append((cid, root, vs))
    with open(out, 'w', encoding='utf-8', newline='\n') as f:
        f.write('# Type trees of Shader (class 48) and ComputeShader (class 72) for every Unity release from 5.5 (f and p builds), generated by dm/gfx/tools/unity_layouts_gen.py\n'
                "# from AssetRipper's TypeTreeDumps (StructsDump/release/<version>.dump). Do not edit by hand: run the script again.\n"
                '# N <id> <align after: 0/1> <type> <name> <child ids...>   (a space in a type or name is written %20; a node comes after its children)\n'
                '# L <class ID> <root node id> <the Unity versions whose dump is exactly this tree...>\n')
        for t, n, a, kids in rows:
            f.write('N %d %d %s %s%s\n' % (ids[t, n, a, kids], a, t.replace(' ', '%20'), n.replace(' ', '%20'), ''.join(' %d' % k for k in kids)))
        for cid, root, vs in roots: f.write('L %d %d %s\n' % (cid, root, ' '.join(vs)))
    return len(rows), len(roots)


def main():
    ap = argparse.ArgumentParser(description=__doc__.split('\n\n')[0])
    ap.add_argument('--cache', type=Path, default=Path(os.environ.get('TMPDIR', '/tmp')) / 'unity_layouts_cache')
    ap.add_argument('--out', type=Path, default=Path(__file__).resolve().parent / 'unity_layouts.txt')
    ap.add_argument('--versions', help='a file listing the versions to read, one per line (default: every f/p release in the repository)')
    a = ap.parse_args()
    a.cache.mkdir(parents=True, exist_ok=True)
    vs = sorted({v.strip() for v in open(a.versions) if v.strip()}, key=vkey) if a.versions else versions()
    with cf.ThreadPoolExecutor(12) as ex: texts = list(ex.map(lambda v: section(v, a.cache), vs))
    layouts = {}
    for v, text in zip(vs, texts):
        for cid, nodes in parse(text).items(): layouts.setdefault((cid, tuple(nodes)), []).append(v)
    n, l = write(layouts, a.out)
    print(f'{len(vs)} Unity versions → {l} layouts, {n} nodes: {a.out}')


if __name__ == '__main__':
    main()
