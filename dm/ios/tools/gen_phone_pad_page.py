#!/usr/bin/env python3
"""Embed dm/ios/phone_pad.html (the phone controller page) in dm/ios/Sources/phone_pad_page.h as a C string, which phone_pads.c serves.
Run after changing the page and commit both; --check exits 1 when the header is stale (dm/ios/tests/test_phone_pads.py)."""
import sys
from pathlib import Path

IOS = Path(__file__).resolve().parents[1]
SRC, OUT = IOS / 'phone_pad.html', IOS / 'Sources/phone_pad_page.h'


def render() -> str:
    data = SRC.read_bytes()
    lines = []
    for i in range(0, len(data), 96):
        chunk = data[i:i + 96]
        lines.append('    "' + ''.join(f'\\x{b:02x}' for b in chunk) + '"')
    return ('// Generated by dm/ios/tools/gen_phone_pad_page.py from dm/ios/phone_pad.html; do not edit.\n'
            '#pragma once\n'
            'static const char phone_pad_page[] =\n' + '\n'.join(lines) + ';\n')


if __name__ == '__main__':
    text = render()
    if '--check' in sys.argv[1:]:
        sys.exit(0 if OUT.exists() and OUT.read_text() == text else 'dm/ios/Sources/phone_pad_page.h is stale: run dm/ios/tools/gen_phone_pad_page.py')
    OUT.write_text(text)
